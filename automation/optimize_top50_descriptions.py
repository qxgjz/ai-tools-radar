# 读取script.js
with open(SCRIPT_JS, "r", encoding="utf-8") as f:
    content = f.read()

# 统计优化数量
optimized_count = 0
skipped_count = 0

# 逐个优化Top 50工具的描述
for tool_name in top50_tools:
    if tool_name not in OPTIMIZED_DESCRIPTIONS:
        print(f"  ⚠️  跳过 {tool_name}（无优化描述）")
        skipped_count += 1
        continue

    new_desc = OPTIMIZED_DESCRIPTIONS[tool_name]

    # 构建正则表达式匹配工具对象
    # 格式: {name:"ToolName",icon:"...",desc:"旧描述",...}
    pattern = r'(\{name:"' + re.escape(tool_name) + r'",icon:"[^"]*",desc:")([^"]*)(")'

    match = re.search(pattern, content)
    if match:
        old_desc = match.group(2)
        # 替换描述
        new_content = content[:match.start(2)] + new_desc + content[match.end(2):]
        content = new_content
        optimized_count += 1
        print(f"  ✅ {tool_name}: 描述已优化 ({len(old_desc)}字 -> {len(new_desc)}字)")
    else:
        print(f"  ❌ {tool_name}: 未找到工具对象")
        skipped_count += 1

# 保存更新后的script.js
with open(SCRIPT_JS, "w", encoding="utf-8") as f:
    f.write(content)

